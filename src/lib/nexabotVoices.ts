export interface NexabotVoice {
  /** Nama voice upstream, mis. "Marco". */
  name: string
  /** Mesin TTS: ElevenLabs | MiniMax | Microsoft. */
  provider: string
  /** Label siap tampil: "Marco · ElevenLabs". */
  label: string
}

export const NEXABOT_VOICES: NexabotVoice[] = NEXABOT_VOICE_TABLE
  .split('\n')
  .map((baris) => baris.trim())
  .filter(Boolean)
  .map((baris) => {
    const [name, provider] = baris.split('|')
    return { name, provider, label: `${name} · ${provider}` }
  })

/** Voice bawaan panel ElevenLabs (sama dengan yang tampil di halaman upstream). */
export const NEXABOT_DEFAULT_VOICE = 'podcast cewe'

/** Cari voice menurut label/nama (case-insensitive) — dipakai UI & tes. */
export function findNexabotVoice(labelOrName: string | null | undefined): NexabotVoice | undefined {
  const cari = String(labelOrName || '').trim().toLowerCase()
  if (!cari) return undefined
  return NEXABOT_VOICES.find((v) => v.label.toLowerCase() === cari)
    || NEXABOT_VOICES.find((v) => v.name.toLowerCase() === cari)
}
